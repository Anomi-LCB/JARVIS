function file(path) {
  return { type: 'file', path, label: path };
}

function contains(path, text) {
  return { type: 'contains', path, text, label: `${path} contains ${text}` };
}

function script(name) {
  return { type: 'script', name, label: `package.json script ${name}` };
}

async function check(item, packageJson) {
  if (item.type === 'script') {
    return {
      ...item,
      pass: Boolean(packageJson.scripts?.[item.name]),
      evidence: packageJson.scripts?.[item.name] ?? null
    };
  }
  if (item.type === 'file') {
    try {
      await access(item.path);
      return { ...item, pass: true, evidence: item.path };
    } catch {
      return { ...item, pass: false, evidence: null };
    }
  }
  const content = await safeRead(item.path);
  return {
    ...item,
    pass: content.includes(item.text),
    evidence: item.path
  };
}

async function safeRead(path) {
  try {
    return await readFile(path, 'utf8');
  } catch {
    return '';
  }
}

function renderMarkdown(report) {
  const lines = [
    '# JARVIS A-G Implementation Audit',
    '',
    `Status: ${report.status}`,
    `Score: ${report.score}`,
    `Generated: ${report.generatedAt}`,
    ''
  ];
  for (const doc of report.docs) {
    lines.push(`## ${doc.id}. ${doc.title}`);
    lines.push(`- Status: ${doc.status}`);
    lines.push(`- Passed: ${doc.passed}/${doc.total}`);
    for (const check of doc.checks) {
      lines.push(`- [${check.pass ? 'x' : ' '}] ${check.label}`);
    }
    lines.push('');
  }
  return `${lines.join('\n')}\n`;
}

export async function runAgAudit({
  jsonPath = 'dist/ag-implementation-audit.json',
  markdownPath = 'dist/ag-implementation-audit.md',
  failOnMissing = false
} = {}) {
  const packageJson = JSON.parse(await readFile('package.json', 'utf8'));
  const checkedDocs = [];
  for (const doc of docs) {
    const checks = [];
    for (const item of doc.checks) checks.push(await check(item, packageJson));
    const passed = checks.filter((item) => item.pass).length;
    checkedDocs.push({
      id: doc.id,
      title: doc.title,
      status: passed === checks.length ? 'complete' : 'incomplete',
      passed,
      total: checks.length,
      checks
    });
  }
  const passed = checkedDocs.reduce((sum, doc) => sum + doc.passed, 0);
  const total = checkedDocs.reduce((sum, doc) => sum + doc.total, 0);
  const report = {
    generatedAt: new Date().toISOString(),
    status: passed === total ? 'complete' : 'incomplete',
    score: Math.round((passed / total) * 100),
    passed,
    total,
    docs: checkedDocs
  };
  await mkdir(dirname(jsonPath), { recursive: true });
  await mkdir(dirname(markdownPath), { recursive: true });
  await writeFile(jsonPath, JSON.stringify(report, null, 2), 'utf8');
  await writeFile(markdownPath, renderMarkdown(report), 'utf8');
  if (failOnMissing && report.status !== 'complete') {
    throw new Error(`A-G audit incomplete: ${passed}/${total}`);
  }
  return report;
}

