import json, subprocess, os, argparse
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
parser=argparse.ArgumentParser()
parser.add_argument('--output',default='artifacts/preference-management-20261003')
parser.add_argument('--restore-race',action='store_true')
parser.add_argument('--restore-before-request',action='store_true')
args=parser.parse_args()
out=Path(args.output);out.mkdir(exist_ok=True)
proc=subprocess.Popen(['node','tests/fixtures/preference-browser.mjs'],stdin=subprocess.PIPE,stdout=subprocess.PIPE,stderr=subprocess.PIPE,text=True,creationflags=subprocess.CREATE_NO_WINDOW if os.name=='nt' else 0)
try:
    ready=json.loads(proc.stdout.readline());errors=[];checks=[]
    with sync_playwright() as p:
        browser=p.chromium.launch(headless=True, channel='chrome')
        page=browser.new_page(viewport={'width':1440,'height':1000})
        page.on('pageerror',lambda e: errors.append(str(e)))
        page.goto(ready['url']);page.locator('summary').click()
        page.get_by_role('button',name='내용 수정',exact=True).wait_for()
        page.get_by_role('button',name='내용 수정',exact=True).click()
        page.get_by_label('정정할 내용').fill('내가 작성 중인 합성 정정 문구')
        if args.restore_before_request:
            page.request.post(ready['url']+'fixture/restore-now')
            page.get_by_role('button',name='수정 저장',exact=True).click()
            expect(page.get_by_role('status')).to_contain_text('기억이 복구되어 저장하지 않았습니다')
            expect(page.get_by_label('정정할 내용')).to_have_value('내가 작성 중인 합성 정정 문구')
            expect(page.get_by_role('button',name='수정 저장',exact=True)).to_be_disabled()
            page.screenshot(path=str(out/'observed-generation-conflict.png'),full_page=True)
            checks.append('pre_request_restore_rejects_same_revision_and_preserves_draft')
            page.get_by_role('button',name='최신 버전 확인 완료',exact=True).click()
        if args.restore_race:
            page.request.post(ready['url']+'fixture/restore-race')
            page.get_by_role('button',name='수정 저장',exact=True).click()
            expect(page.get_by_role('status')).to_contain_text('기억이 복구되어 저장하지 않았습니다')
            expect(page.get_by_label('정정할 내용')).to_have_value('내가 작성 중인 합성 정정 문구')
            expect(page.get_by_role('button',name='수정 저장',exact=True)).to_be_disabled()
            page.screenshot(path=str(out/'restore-conflict.png'),full_page=True)
            checks.append('restore_generation_conflict_preserves_draft_and_requires_review')
            page.get_by_role('button',name='최신 버전 확인 완료',exact=True).click()
        page.request.post(ready['url']+'fixture/change')
        page.get_by_role('button',name='수정 저장',exact=True).click()
        expect(page.get_by_role('status')).to_contain_text('다른 곳에서 먼저 수정')
        expect(page.get_by_label('정정할 내용')).to_have_value('내가 작성 중인 합성 정정 문구')
        expect(page.get_by_role('button',name='수정 저장',exact=True)).to_be_disabled()
        expect(page.locator('article > p')).to_have_text('다른 창에서 먼저 정정한 합성 선호')
        checks.append('conflict_latest_value_and_unsent_draft_preserved')
        page.get_by_role('button',name='최신 버전 확인 완료',exact=True).click()
        page.get_by_role('button',name='수정 저장',exact=True).click()
        expect(page.get_by_role('status')).to_have_text('기억을 수정했습니다.')
        expect(page.locator('article > p')).to_have_text('내가 작성 중인 합성 정정 문구')
        checks.append('explicit_rebase_and_actual_core_sqlite_save')
        page.get_by_role('button',name='사용 중지',exact=True).click()
        expect(page.get_by_role('heading',name='사용을 중지한 선호')).to_be_visible()
        expect(page.get_by_role('button',name='내용 수정',exact=True)).to_have_count(0)
        checks.append('withdrawal_removes_edit_controls')
        page.request.post(ready['url']+'fixture/retract')
        page.get_by_role('button',name='새로 확인',exact=True).click()
        expect(page.get_by_role('heading',name='원자료가 철회된 기억')).to_be_visible()
        assert '내가 작성 중인 합성 정정 문구' not in page.locator('body').inner_text()
        expect(page.locator('textarea')).to_have_count(0)
        checks.append('retracted_content_and_editor_withheld')
        page.screenshot(path=str(out/'desktop.png'),full_page=True)
        page.set_viewport_size({'width':390,'height':844})
        overflow=page.evaluate('Math.max(0,document.documentElement.scrollWidth-innerWidth)')
        assert overflow==0,overflow
        page.screenshot(path=str(out/'mobile.png'),full_page=True)
        checks.append('mobile_no_horizontal_overflow')
        assert not errors, errors
        browser.close()
    result={'mode':'isolated-browser-real-core-sqlite','checks':checks,'passed':len(checks),'pageErrors':errors,'horizontalOverflowPx':overflow,'syntheticDataOnly':True,'productionModified':False,'url':ready['url']}
    (out/'browser.json').write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps(result,ensure_ascii=False))
finally:
    stdout,stderr=proc.communicate('close\n',timeout=15)
    assert proc.returncode==0,stderr[-1800:]
