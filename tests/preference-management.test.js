const escape = value => String(value).replace(/[&<>"']/gu, c => ({ '&':'&amp;', '<':'&lt;', '>':'&gt;', '"':'&quot;', "'":'&#39;' })[c]);
test('Core preference API enforces admin, bounded correction, revision conflict and source retraction', async t => {
  const root = mkdtempSync(join(tmpdir(), 'jarvis-preference-screen-'));
  const store = new SqliteMemoryStore({ dbPath: join(root, 'memory.sqlite'), reviewDir: join(root, 'reviews'), backupDir: join(root, 'backups') });
  const growth = new GrowthRuntime({ memoryStore: store, auditRoot: root });
  const scope = { userId: 'synthetic-owner', workspaceRoot: root, conversationId: null };
  for (let i = 1; i <= 3; i++) growth.ingestor.ingest({ eventId: `evt-${i}`, taskId: `task-${i}`, eventType: 'approval.edited', source: { module: 'CORE', memoryScope: scope }, payload: { editRequest: '자료를 표로 정리해줘' }, learningFlags: { canBeUsedForPreference: true }, trustBoundary: { userProvided: true } });
  const candidate = growth.query('자료', { scope }).find(item => item.hypothesisId);
  const result = growth.decidePreference({ hypothesisId: candidate.hypothesisId }); assert.equal(result.success, true);
  const id = result.item.preferenceId;
  const server = createCoreServer(new CoreFacade({ memoryStore: growth, workspaceRoot: root }), { adminToken: 'synthetic-admin', adminTokens: [{ token: 'synthetic-reader', scopes: ['read_diagnostics'] }] });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await new Promise(resolve => { server.closeAllConnections(); server.close(resolve); }); store.close(); rmSync(root, { recursive: true, force: true }); });
  const call = (suffix = '', method = 'GET', body, token = 'synthetic-admin') => fetch(`http://127.0.0.1:${server.address().port}/memory/preferences${suffix}`, { method, headers: { authorization: `Bearer ${token}`, 'content-type': 'application/json' }, ...(body ? { body: JSON.stringify(body) } : {}) });
  assert.equal((await call('', 'GET', null, 'wrong')).status, 401);
  assert.equal((await call('', 'GET', null, 'synthetic-reader')).status, 403);
  const initial = await (await call()).json(); assert.equal(initial.items.length, 1); assert.equal(initial.items[0].history, undefined);
  assert.equal((await call(`/${id}`, 'PATCH', { expectedRevision: 1, expectedGeneration: 0, statement: '자료를 짧게 정리한다', status: 'confirmed' })).status, 400);
  assert.equal((await call(`/${id}`, 'PATCH', { statement: '정정' })).status, 400);
  assert.equal((await call(`/${id}`, 'PATCH', { expectedRevision: 1, expectedGeneration: 0, statement: '자료를 짧게 정리한다' })).status, 200);
  assert.equal((await call(`/${id}`, 'PATCH', { expectedRevision: 1, expectedGeneration: 0, statement: '오래된 수정' })).status, 409);
  assert.equal(store.getConfirmedPreference(id).statement, '자료를 짧게 정리한다');
  growth.decideHygiene({ targetId: 'evt-1', action: 'delete' });
  const item = (await (await call()).json()).items[0]; assert.equal(item.contentWithheld, true); assert.equal(item.statement.includes('짧게'), false);
  const forbidden = await call(`/${id}`, 'PATCH', { expectedRevision: item.revision, expectedGeneration: 0, statement: '다시 사용' });
  assert.equal(forbidden.status, 409); assert.equal((await forbidden.json()).error.code, 'F_MEMORY_SOURCE_RETRACTED');
  assert.equal((await call(`/${id}/revoke`, 'POST', { expectedRevision: item.revision, expectedGeneration: 0 })).status, 200);
});
test('panel escapes content, retains conflicting draft and never silently retries or enables withdrawn content', async () => {
  let revision = 1, status = 'confirmed', calls = [], blocked = false;
  const panel = createPreferenceManagementPanel({ canManage: () => true, escape, request: async (path, options) => {
    calls.push({ path, options });
    if (!options) return { memoryGeneration: 0, items: [{ preferenceId: 'p1', revision, status, statement: '<img src=x> 최신 내용', contentWithheld: blocked }] };
    if (options.body.expectedRevision !== revision) throw { code: 'F_MEMORY_REVISION_CONFLICT' };
    return { success: true, item: { preferenceId: 'p1' } };
  } });
  await panel.refresh(); panel.edit('p1'); revision = 2;
  await panel.mutate('p1', 'save');
  assert.equal(calls.filter(call => call.options).length, 1);
  assert.equal(calls.find(call => call.options).options.body.expectedRevision, 1);
  assert.match(panel.render(), /다른 곳에서 먼저 수정/); assert.match(panel.render(), /최신 버전 확인 완료/);
  assert.doesNotMatch(panel.render(), /<img src=x>/); assert.match(panel.render(), /&lt;img src=x&gt;/);
  await panel.mutate('p1', 'save'); assert.equal(calls.filter(call => call.options).length, 1);
  blocked = true; status = 'source_review_required'; await panel.refresh();
  const html = panel.render(); assert.doesNotMatch(html, /data-preference-edit=/);
  assert.doesNotMatch(html, /<img src=x>/); assert.match(html, /원자료가 철회된 기억/);
  const locked = createPreferenceManagementPanel({ canManage: () => false, request: () => { throw new Error('must not call'); } });
  await locked.refresh(); assert.match(locked.render(), /관리자 연결/);
});

test('Core publishes revision-required preference contracts and production UI wires the panel', async () => {
  const paths = createCoreOpenApiSpec().paths;
  assert.equal(paths['/memory/preferences'].get.security[0].bearerAuth.length, 0);
  const schema = paths['/memory/preferences/{preferenceId}'].patch.requestBody.content['application/json'].schema;
  assert.deepEqual(schema.required, ['expectedRevision', 'expectedGeneration', 'statement']);
  assert.equal(schema.additionalProperties, false);
  assert.ok(paths['/memory/preferences/{preferenceId}'].patch.responses[409]);
  const { readFile } = await import('node:fs/promises');
  const source = await readFile(new URL('../src/ui/app.js', import.meta.url), 'utf8');
  assert.ok(source.includes('createPreferenceManagementPanel'));
  assert.ok(source.includes('${preferenceManagementPanel.render()}'));
  assert.ok(source.includes('preferenceManagementPanel.attach(app)'));
  assert.ok(source.includes('preferenceManagementPanel.refresh()'));
});
