import test from 'node:test';import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';import {tmpdir} from 'node:os';import {join} from 'node:path';
import {SqliteMemoryStore} from '../apps/growth-memory/src/db/sqlite-store.js';import {GrowthRuntime} from '../apps/growth-memory/src/growth-runtime.js';
import {CoreFacade} from '../packages/core/src/core-facade.js';
test('scoped recall uses current assertions and preserves reason without deriving workflow authority',t=>{
 const root=mkdtempSync(join(tmpdir(),'jarvis-knowledge-recall-'));const scope={userId:'synthetic-user',workspaceRoot:root,conversationId:'thread'};
 let now=new Date('2026-02-25T00:00:00.000Z');
 const opts={clock:()=>now,dbPath:join(root,'f.sqlite'),reviewDir:join(root,'reviews'),backupDir:join(root,'backups')};let store=new SqliteMemoryStore(opts);
 let growth=new GrowthRuntime({memoryStore:store,auditRoot:root,clock:()=>now});
 t.after(()=>{store.close();rmSync(root,{recursive:true,force:true});});
 const put=(id,value,extra={},at='2026-02-20T00:00:00.000Z')=>growth.ingest({eventId:id,taskId:id,eventType:'task.created',createdAt:at,source:{module:'CORE',memoryScope:scope},
  payload:{rawText:'합성 프로젝트 기억',knowledge:{kind:'decision',subject:'합성 프로젝트',predicate:'실행 위치',value,reason:'오프라인 작업',...extra}},learningFlags:{canBeUsedForWorkflow:true},trustBoundary:{userProvided:true,systemGenerated:false}},{expectedKnowledgeSource:extra.supersedesEventId?{eventId:extra.supersedesEventId,observedAt:growth.personalKnowledge({scope}).find(x=>x.sourceEventId===extra.supersedesEventId).observedAt}:null});
 put('old','이전 위치');put('new','새 위치',{supersedesEventId:'old',validUntil:'2026-02-26T00:00:00.000Z'},'2026-02-21T00:00:00.000Z');
 let recalled=growth.query('합성 프로젝트',{scope});
 assert.equal(recalled.some(x=>x.memoryType==='personal_knowledge'&&x.value==='새 위치'),true);
 assert.equal(JSON.stringify(recalled).includes('이전 위치'),false);
 const current=recalled.find(x=>x.memoryType==='personal_knowledge');assert.equal(current.reason,'오프라인 작업');assert.equal(current.executionAuthority,false);assert.deepEqual(current.provenance.sourceEventIds,['new']);
 assert.deepEqual(growth.query('합성 프로젝트',{scope:{...scope,conversationId:'other'}}),[]);
 store.close();store=new SqliteMemoryStore(opts);growth=new GrowthRuntime({memoryStore:store,auditRoot:root,clock:()=>now});
 assert.equal(growth.query('합성 프로젝트',{scope}).some(x=>x.value==='새 위치'),true);
 const core=new CoreFacade({workspaceRoot:root,memoryStore:growth});
 const options={userId:scope.userId,metadata:{conversationId:scope.conversationId}};
 const task=core.createTask('합성 프로젝트 자료를 확인해줘',options);
 assert.equal(task.memoryContext.some(x=>x.memoryType==='personal_knowledge'&&x.value==='새 위치'),true);
 assert.equal(JSON.stringify(task.memoryContext).includes('이전 위치'),false);
 const evidence=task.contextSnapshot.memoryEvidence.find(x=>x.sourceEventIds.includes('new'));
 assert.deepEqual(evidence.validity,{validUntil:'2026-02-26T00:00:00.000Z',basis:'declared-expiry'});
 assert.deepEqual(evidence.usageScopes,[scope]);
 assert.deepEqual(evidence.revisionReference,{revision:null,supersedesEventId:'old'});
 assert.equal(JSON.stringify(evidence).includes('이전 위치'),false);
 assert.deepEqual(core.createTask('합성 프로젝트 자료를 확인해줘',{...options,metadata:{...options.metadata,longTermMemory:false}}).memoryContext,[]);
 put('conflict','충돌 위치',{},'2026-02-22T00:00:00.000Z');
 assert.equal(growth.query('합성 프로젝트',{scope}).some(x=>x.memoryType==='personal_knowledge'),false);
 const issue=growth.query('합성 프로젝트',{scope}).find(x=>x.memoryType==='personal_knowledge_issue');
 assert.equal(issue.requiresUserResolution,true);assert.equal(issue.value,undefined);assert.equal(issue.executionAuthority,false);
 assert.equal(growth.planningPreferenceContext('합성 프로젝트',{scope}).workflowHints.length,0);
 growth.decideHygiene({targetId:'conflict',action:'delete'});
 assert.equal(growth.query('합성 프로젝트',{scope}).some(x=>x.value==='새 위치'),true);
 now=new Date('2026-02-23T12:00:00.000Z');
 put('expired','만료 위치',{supersedesEventId:'new',validUntil:'2026-02-24T00:00:00.000Z'},'2026-02-23T00:00:00.000Z');
 now=new Date('2026-02-25T00:00:00.000Z');
 put('future','미래 위치',{},'2199-02-20T00:00:00.000Z');
 assert.equal(growth.query('합성 프로젝트',{scope}).some(x=>x.memoryType==='personal_knowledge'),false);
 assert.equal(growth.memoryContext('합성 프로젝트',{scope}).workflowHints.length,0);
 core.cognition?.close();
});
