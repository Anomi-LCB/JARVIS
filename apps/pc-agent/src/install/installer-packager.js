function renderLaunchTrayScript() {
  return [
    '# Generated by JARVIS PC Agent installer packager.',
    '$ErrorActionPreference = "Stop"',
    '$root = Split-Path -Parent $MyInvocation.MyCommand.Path',
    '$trayExe = Join-Path $root "JarvisPcAgentTray.exe"',
    '$trayScript = Join-Path $root "tray-agent.ps1"',
    'if (Test-Path $trayExe) {',
    '  Start-Process $trayExe',
    '} else {',
    '  Start-Process powershell.exe -WindowStyle Hidden -ArgumentList @("-NoProfile", "-ExecutionPolicy", "Bypass", "-STA", "-File", "`"$trayScript`"")',
    '}',
    'Write-Host "JARVIS PC Agent tray launch requested."'
  ].join('\n');
}

function renderBuildTrayExeScript() {
  return [
    '# Generated by JARVIS PC Agent installer packager.',
    '$ErrorActionPreference = "Stop"',
    '$root = Split-Path -Parent $MyInvocation.MyCommand.Path',
    '$source = Join-Path $root "tray-agent.cs"',
    '$output = Join-Path $root "JarvisPcAgentTray.exe"',
    '$candidateCompilers = @(',
    '  (Join-Path $env:WINDIR "Microsoft.NET\\Framework64\\v4.0.30319\\csc.exe"),',
    '  (Join-Path $env:WINDIR "Microsoft.NET\\Framework\\v4.0.30319\\csc.exe")',
    ')',
    '$dotnet = Get-Command dotnet -ErrorAction SilentlyContinue',
    'if ($dotnet) {',
    '  $sdkRoot = & $dotnet.Path --list-sdks | Select-Object -Last 1',
    '  if ($sdkRoot) {',
    '    $sdkVersion = ($sdkRoot -split " ")[0]',
    '    $sdkPath = Join-Path (Split-Path $dotnet.Path -Parent) "sdk\\$sdkVersion\\Roslyn\\bincore\\csc.dll"',
    '    if (Test-Path $sdkPath) {',
    '      & $dotnet.Path $sdkPath -target:winexe -out:$output -r:System.Windows.Forms.dll -r:System.Drawing.dll $source',
    '      if ($LASTEXITCODE -ne 0) { throw "C# tray build failed with exit code $LASTEXITCODE." }',
    '      if (-not (Test-Path $output)) { throw "C# tray build did not create $output" }',
    '      Write-Host "Built native tray executable: $output"',
    '      exit 0',
    '    }',
    '  }',
    '}',
    '$csc = $candidateCompilers | Where-Object { Test-Path $_ } | Select-Object -First 1',
    'if (-not $csc) { throw "No C# compiler found. Install .NET SDK or Windows .NET Framework build tools." }',
    '& $csc /target:winexe /out:$output /reference:System.Windows.Forms.dll /reference:System.Drawing.dll $source',
    'if ($LASTEXITCODE -ne 0) { throw "C# tray build failed with exit code $LASTEXITCODE." }',
    'if (-not (Test-Path $output)) { throw "C# tray build did not create $output" }',
    'Write-Host "Built native tray executable: $output"'
  ].join('\n');
}

